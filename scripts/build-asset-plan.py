def style_header_row(ws, n_cols):
    fill = PatternFill("solid", fgColor=NAVY)
    font = Font(name="Calibri", size=11, bold=True, color=WHITE)
    align = Alignment(horizontal="left", vertical="center", wrap_text=True)
    for c in range(1, n_cols + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = fill
        cell.font = font
        cell.alignment = align
    ws.row_dimensions[1].height = 36


def set_widths(ws, widths):
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def apply_priority_formatting(ws, n_cols, n_rows, pri_col_idx):
    align_top_left = Alignment(horizontal="left", vertical="top", wrap_text=True)
    for r in range(2, n_rows + 2):
        for c in range(1, n_cols + 1):
            ws.cell(row=r, column=c).alignment = align_top_left
        pri_cell = ws.cell(row=r, column=pri_col_idx)
        pri = str(pri_cell.value or "").strip()
        if pri in PRI_FILL:
            pri_cell.fill = PatternFill("solid", fgColor=PRI_FILL[pri])
            pri_cell.font = Font(name="Calibri", size=11, bold=True)


def write_asset_sheet(wb, sheet_name, rows):
    ws = wb.create_sheet(sheet_name)
    set_widths(ws, WIDTHS)
    ws.append(HEADERS)
    style_header_row(ws, len(HEADERS))

    for row_dict in rows:
        ws.append([row_dict.get(h, "") for h in HEADERS])

    pri_col_idx = HEADERS.index("Priority") + 1
    apply_priority_formatting(ws, len(HEADERS), len(rows), pri_col_idx)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions


